#!/usr/bin/env python3
"""Generate optimised Crazyflie waypoints using the pdSTL planner from src/.

Usage (from this folder):
    python generate_waypoints.py [--fan {2,6,12,16}] [--plot]

Output:
    Overwrites components/opt_waypoints.py with a WAYPOINTS list.
    T+1=11 tuples (x, y, z), including the initial position.
"""

from __future__ import annotations

import pathlib

import argparse
import datetime
import math

import numpy as np
import torch

from components.environment_config import (
    DT,
    BeliefTrajectory,
    Environment,
    FLIGHT_X_BOUNDS,
    FLIGHT_Y_BOUNDS,
    PLANNER_ALPHA,
    T,
    TorchGaussianBelief,
    Z_HEIGHT,
    build_planner,
    sine_warm_start_waypoints,
    x0_belief,
)

HERE = pathlib.Path(__file__).resolve().parent

X0_MEAN, X0_COV = x0_belief()


def z_profile(xy_waypoints: np.ndarray) -> list[float]:
    """Altitude for each waypoint.

    Constant for now (2D planning at fixed height). For 3D flights later,
    replace this with a real profile — nothing else needs restructuring.
    """
    return [Z_HEIGHT] * len(xy_waypoints)


_sine_waypoints = sine_warm_start_waypoints


def _validate_waypoints_inside_flight_area(waypoints: list[tuple[float, float, float]]) -> None:
    x_min, x_max = FLIGHT_X_BOUNDS
    y_min, y_max = FLIGHT_Y_BOUNDS
    outside = [
        (idx, x, y)
        for idx, (x, y, _z) in enumerate(waypoints)
        if not (x_min <= x <= x_max and y_min <= y <= y_max)
    ]
    if outside:
        details = ', '.join(f'#{idx}=({x:.3f}, {y:.3f})' for idx, x, y in outside)
        raise ValueError(
            'Generated waypoint(s) outside flight area '
            f'x=[{x_min}, {x_max}], y=[{y_min}, {y_max}]: {details}'
        )


def _sine_init_guess() -> torch.Tensor:
    """Convert sine waypoints to T=10 velocity controls for warm-starting."""
    wps = np.array(_sine_waypoints())
    vels = np.diff(wps[:, :2], axis=0) / DT  # (9, 2)
    vels = np.vstack([vels, [[0.0, 0.0]]])
    return torch.tensor(vels, dtype=torch.float32)


def _evaluate_rho(planner, init_u: torch.Tensor) -> float:
    """Evaluate STL P(sat) for a given control sequence without optimising."""
    u_norm = torch.clamp(init_u / planner.dyn.u_max, -0.99, 0.99)
    v = 0.5 * torch.log((1 + u_norm) / (1 - u_norm))
    with torch.no_grad():
        mean_trace, cov_trace = planner.dyn(v, X0_MEAN, X0_COV)
        beliefs = [TorchGaussianBelief(mean_trace[:, t, :], cov_trace[:, t]) for t in range(T + 1)]
        phi = planner.env.get_specification(T)
        return phi(BeliefTrajectory(beliefs))[0, 0, 0].item()


def _write_waypoints(
    path: pathlib.Path,
    waypoints: list[tuple[float, float, float]],
    rho_before: float,
    rho_after: float,
    alpha: float,
    fan: int,
) -> None:
    ts = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%S+00:00')
    lines = [
        '# Auto-generated by generate_waypoints.py; do not edit by hand.',
        f'# generated={ts}  rho_before={rho_before:.4f}  rho_after={rho_after:.4f}  alpha={alpha}  fan={fan}',
        '',
        'WAYPOINTS: list[tuple[float, float, float]] = [',
    ]
    for x, y, z in waypoints:
        lines.append(f'    ({x:.6f}, {y:.6f}, {z}),')
    lines += [']', '']
    path.write_text('\n'.join(lines), encoding='utf-8')


def _plot(
    env: Environment,
    sine_wps: np.ndarray,
    opt_xy: np.ndarray,
    opt_cov: np.ndarray,
) -> None:
    import matplotlib.patches as patches
    import matplotlib.pyplot as plt
    from matplotlib.patches import Ellipse

    fig, axes = plt.subplots(1, 2, figsize=(14, 7))
    for ax, (path_xy, title, draw_ellipses) in zip(
        axes,
        [
            (sine_wps[:, :2], 'Before (Sine Path)', False),
            (opt_xy, 'After (pdSTL Optimised)', True),
        ],
    ):
        ax.set_title(title)
        ax.set_aspect('equal')
        ax.set_xlim(FLIGHT_X_BOUNDS[0] - 0.1, FLIGHT_X_BOUNDS[1] + 0.1)
        ax.set_ylim(FLIGHT_Y_BOUNDS[0] - 0.1, FLIGHT_Y_BOUNDS[1] + 0.1)
        ax.grid(True, alpha=0.3)

        ax.add_patch(
            patches.Rectangle(
                (FLIGHT_X_BOUNDS[0], FLIGHT_Y_BOUNDS[0]),
                FLIGHT_X_BOUNDS[1] - FLIGHT_X_BOUNDS[0],
                FLIGHT_Y_BOUNDS[1] - FLIGHT_Y_BOUNDS[0],
                facecolor='none',
                edgecolor='black',
                linestyle='--',
                linewidth=1.2,
                label='flight area',
            )
        )

        for obs in env.obstacles:
            ox, oy = obs['x'], obs['y']
            ax.add_patch(
                patches.Rectangle(
                    (ox[0], oy[0]),
                    ox[1] - ox[0],
                    oy[1] - oy[0],
                    facecolor='red',
                    alpha=0.4,
                    edgecolor='darkred',
                )
            )

        if env.goal:
            gx, gy = env.goal['x'], env.goal['y']
            ax.add_patch(
                patches.Rectangle(
                    (gx[0], gy[0]),
                    gx[1] - gx[0],
                    gy[1] - gy[0],
                    facecolor='green',
                    alpha=0.3,
                    edgecolor='darkgreen',
                )
            )

        ax.plot(path_xy[:, 0], path_xy[:, 1], 'b.-', lw=2, ms=8)
        ax.plot(path_xy[0, 0], path_xy[0, 1], 'go', ms=10, label='start')
        ax.plot(path_xy[-1, 0], path_xy[-1, 1], 'rs', ms=10, label='end')

        if draw_ellipses:
            for t in range(len(opt_xy)):
                cov_t = opt_cov[t]
                vals, vecs = np.linalg.eigh(cov_t)
                angle = math.degrees(math.atan2(*vecs[:, -1][::-1]))
                w, h = 2 * 2 * np.sqrt(np.maximum(vals, 0))
                el = Ellipse(
                    xy=opt_xy[t],
                    width=w,
                    height=h,
                    angle=angle,
                    edgecolor='blue',
                    facecolor='none',
                    alpha=0.5,
                    lw=0.8,
                )
                ax.add_patch(el)

        ax.legend()

    plt.tight_layout()
    out = HERE / 'waypoints_comparison.png'
    plt.savefig(out, dpi=150)
    print(f'Plot saved to {out}')
    plt.show()


# ── Main ─────────────────────────────────────────────────────────────────────


def main() -> None:
    parser = argparse.ArgumentParser(description='Generate optimised Crazyflie waypoints via pdSTL')
    parser.add_argument(
        '--fan',
        type=int,
        default=2,
        choices=[2, 6, 12, 16],
        help='Fan speed level; selects process noise Q for planner',
    )
    parser.add_argument('--plot', action='store_true', help='Show before/after path plot')
    args = parser.parse_args()

    planner, _dynamics, env = build_planner(args.fan)

    init_u = _sine_init_guess()

    rho_before = _evaluate_rho(planner, init_u)
    print(f'rho_before (sine path): {rho_before:.4f}')

    best_mean, best_cov, _best_u, best_p, _history = planner._optimize_window(
        X0_MEAN,
        X0_COV,
        init_guess=init_u,
        verbose=True,
    )
    print(f'rho_after  (optimised):  {best_p:.4f}')

    positions_xy = best_mean.squeeze(0).cpu().numpy()
    z_values = z_profile(positions_xy)
    waypoints = [(float(x), float(y), z) for (x, y), z in zip(positions_xy, z_values)]
    _validate_waypoints_inside_flight_area(waypoints)

    out_path = HERE / 'components' / 'opt_waypoints.py'
    _write_waypoints(out_path, waypoints, rho_before, best_p, PLANNER_ALPHA, args.fan)
    print(f'Written {len(waypoints)} waypoints to {out_path}')

    if args.plot:
        sine_wps = np.array(_sine_waypoints())
        _plot(env, sine_wps, positions_xy, best_cov.squeeze(0).cpu().numpy())


if __name__ == '__main__':
    main()
